    END IF;
END
$$;

-- Al reabrir (o anular) un ticket resuelto, la calificación ya no aplica
CREATE OR REPLACE FUNCTION tg_incidencias_calificacion() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_nuevo_estado CITEXT;
BEGIN
    IF NEW.calificacion IS NOT NULL AND NEW.idestado IS DISTINCT FROM OLD.idestado THEN
        SELECT e.nombre INTO v_nuevo_estado FROM estados e WHERE e.idestado = NEW.idestado;
        IF v_nuevo_estado IS DISTINCT FROM 'Resuelto' AND v_nuevo_estado IS DISTINCT FROM 'Cerrado' THEN
            NEW.calificacion      := NULL;
            NEW.fechacalificacion := NULL;
        END IF;
    END IF;
    RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS trg_incidencias_calificacion ON incidencias;
CREATE TRIGGER trg_incidencias_calificacion
    BEFORE UPDATE ON incidencias
    FOR EACH ROW EXECUTE FUNCTION tg_incidencias_calificacion();

