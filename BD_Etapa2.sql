DROP FUNCTION IF EXISTS sp_tiposincidencia_listar(BOOLEAN);
CREATE FUNCTION sp_tiposincidencia_listar(p_soloactivos BOOLEAN DEFAULT FALSE)
RETURNS TABLE (idtipoincidencia INT, nombre CITEXT, activo BOOLEAN, totalincidencias INT)
LANGUAGE sql STABLE AS $$
    SELECT t.idtipoincidencia, t.nombre, t.activo,
           (SELECT COUNT(*)::int FROM incidencias i WHERE i.idtipoincidencia = t.idtipoincidencia)
    FROM tiposincidencia t
    WHERE NOT p_soloactivos OR t.activo
    ORDER BY t.nombre ASC;
$$;

CREATE OR REPLACE FUNCTION sp_tiposincidencia_insertar(p_nombre VARCHAR, p_activo BOOLEAN DEFAULT TRUE)
RETURNS INT LANGUAGE sql AS $$
    INSERT INTO tiposincidencia (nombre, activo) VALUES (btrim(p_nombre), p_activo)
    RETURNING idtipoincidencia;
$$;

-- Al renombrar, los tickets de ese tipo muestran el nombre nuevo
CREATE OR REPLACE FUNCTION sp_tiposincidencia_modificar(p_idtipoincidencia INT, p_nombre VARCHAR, p_activo BOOLEAN)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    UPDATE tiposincidencia
    SET nombre = btrim(p_nombre), activo = p_activo
    WHERE idtipoincidencia = p_idtipoincidencia;

    UPDATE incidencias
    SET tipoincidencia = btrim(p_nombre)
    WHERE idtipoincidencia = p_idtipoincidencia
      AND tipoincidencia IS DISTINCT FROM btrim(p_nombre);
END
$$;

-- Devuelve 1 = eliminado, 0 = tenía tickets y solo se desactivó (para no perder el historial)
CREATE OR REPLACE FUNCTION sp_tiposincidencia_eliminar(p_idtipoincidencia INT)
RETURNS INT LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM incidencias i WHERE i.idtipoincidencia = p_idtipoincidencia) THEN
        UPDATE tiposincidencia SET activo = FALSE WHERE idtipoincidencia = p_idtipoincidencia;
        RETURN 0;
    END IF;
    DELETE FROM tiposincidencia WHERE idtipoincidencia = p_idtipoincidencia;
    RETURN 1;
END
$$;

