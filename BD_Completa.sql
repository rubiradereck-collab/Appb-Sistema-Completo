-- LISTAR (con JOINs para traer los nombres en lugar de solo IDs)
CREATE OR REPLACE FUNCTION sp_incidencias_listar()
RETURNS TABLE (idincidencia INT, numeroticket VARCHAR, fecha TIMESTAMP, empleado VARCHAR,
               idarea INT, nombrearea CITEXT, tipoincidencia VARCHAR, descripcion TEXT,
               idprioridad INT, nombreprioridad CITEXT, idestado INT, nombreestado CITEXT,
               idtecnicoasignado INT, tecnicoasignado VARCHAR, fechasolucion TIMESTAMP,
               observaciones TEXT, filaversion BYTEA)
LANGUAGE sql STABLE AS $$
    SELECT
        i.idincidencia,
        i.numeroticket,
        i.fecha,
        i.empleado,
        i.idarea,
        a.nombrearea,
        i.tipoincidencia,
        i.descripcion,
        i.idprioridad,
        p.nombre AS nombreprioridad,
        i.idestado,
        e.nombre AS nombreestado,
        i.idtecnicoasignado,
        (u.nombre || ' ' || u.apellido)::VARCHAR AS tecnicoasignado,
        i.fechasolucion,
        i.observaciones,
        int8send(i.filaversion) AS filaversion
    FROM incidencias i
    INNER JOIN areas a       ON i.idarea = a.idarea
    INNER JOIN prioridades p ON i.idprioridad = p.idprioridad
    INNER JOIN estados e     ON i.idestado = e.idestado
    LEFT JOIN usuarios u     ON i.idtecnicoasignado = u.idusuario
    ORDER BY i.fecha DESC;
$$;

-- INSERTAR: devuelve el Id generado (antes: RETURN SCOPE_IDENTITY())
CREATE OR REPLACE FUNCTION sp_incidencias_insertar(
    p_empleado          VARCHAR,
    p_idarea            INT,
    p_tipoincidencia    VARCHAR,
    p_descripcion       TEXT,
    p_idprioridad       INT,
    p_idestado          INT,
    p_idtecnicoasignado INT  DEFAULT NULL,
    p_observaciones     TEXT DEFAULT NULL)
RETURNS INT LANGUAGE sql AS $$
    INSERT INTO incidencias (empleado, idarea, tipoincidencia, descripcion, idprioridad, idestado, idtecnicoasignado, observaciones)
    VALUES (p_empleado, p_idarea, p_tipoincidencia, p_descripcion, p_idprioridad, p_idestado, p_idtecnicoasignado, p_observaciones)
    RETURNING idincidencia;
$$;

-- MODIFICAR: devuelve filas afectadas (0 = otra persona la modificó antes)
CREATE OR REPLACE FUNCTION sp_incidencias_modificar(
    p_idincidencia        INT,
    p_empleado            VARCHAR,
    p_idarea              INT,
    p_tipoincidencia      VARCHAR,
    p_descripcion         TEXT,
    p_idprioridad         INT,
    p_idestado            INT,
    p_idtecnicoasignado   INT,
    p_fechasolucion       TIMESTAMP,
    p_observaciones       TEXT,
    p_filaversionoriginal BYTEA)
RETURNS INT LANGUAGE plpgsql AS $$
DECLARE
    v_filas INT;
BEGIN
    UPDATE incidencias
    SET empleado          = p_empleado,
        idarea            = p_idarea,
        tipoincidencia    = p_tipoincidencia,
        descripcion       = p_descripcion,
        idprioridad       = p_idprioridad,
        idestado          = p_idestado,
        idtecnicoasignado = p_idtecnicoasignado,
        fechasolucion     = p_fechasolucion,
        observaciones     = p_observaciones
    WHERE incidencias.idincidencia = p_idincidencia
      AND int8send(incidencias.filaversion) = p_filaversionoriginal;

    GET DIAGNOSTICS v_filas = ROW_COUNT;
    RETURN v_filas;
END
$$;

