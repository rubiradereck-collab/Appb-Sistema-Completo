DO $$
DECLARE
    f RECORD;
    t TEXT;
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'appb_app') THEN
        FOREACH t IN ARRAY ARRAY['guiasenvios', 'guiasenviosdetalle', 'lineabase'] LOOP
