/* ============================================================================
   Sistema de Gestión de Incidencias APPB — Base de datos PostgreSQL
   Migrado desde SQL Server (ver BD_Completa_SQLServer.sql).

   Uso (desde psql, conectado como superusuario o dueño de la BD):
       CREATE DATABASE dbincidencias;
       \c dbincidencias
       \i BD_Completa.sql
       \i BD_Etapa2.sql        (catálogo de tipos, fechas de asignación, estado Anulado)

   Notas de la migración:
   - Los nombres de tablas, columnas y funciones van sin comillas, así que
     PostgreSQL los guarda en minúsculas (Incidencias -> incidencias). Las
     consultas pueden seguir escribiéndolos como antes (IdIncidencia, etc.).
   - Los procedimientos almacenados sp_* ahora son FUNCIONES con el mismo
     nombre y los mismos parámetros: SELECT * FROM sp_incidencias_listar();
   - SQL Server compara texto sin distinguir mayúsculas; aquí se usa CITEXT
     en las columnas que se comparan o son únicas (usuario, correo, rol,
     nombres de catálogos) para conservar ese comportamiento.
   - [timestamp]/rowversion de FilaVersion se reemplaza por un contador BIGINT
     que un trigger incrementa en cada UPDATE. Se expone como bytea (8 bytes)
     para que la aplicación lo siga tratando como byte[].
   - GETDATE() -> LOCALTIMESTAMP. La zona horaria de la BD se fija en
     America/Guayaquil para que las fechas sigan siendo hora local.
   ============================================================================ */

CREATE EXTENSION IF NOT EXISTS citext;

-- Hora local de Ecuador para LOCALTIMESTAMP en todas las sesiones de esta BD
DO $$
BEGIN
    EXECUTE format('ALTER DATABASE %I SET timezone TO %L', current_database(), 'America/Guayaquil');
END
$$;
SET timezone TO 'America/Guayaquil';

