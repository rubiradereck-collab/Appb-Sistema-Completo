/* ----------------------------------------------------------------------------
   5. Trigger con las reglas de negocio
   ---------------------------------------------------------------------------- */

CREATE OR REPLACE FUNCTION tg_incidencias_reglas() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_nuevo_estado    CITEXT;
    v_anterior_estado CITEXT;
    v_nombre_tipo     CITEXT;
BEGIN
    SELECT e.nombre INTO v_nuevo_estado FROM estados e WHERE e.idestado = NEW.idestado;

    -- Tipo: el catálogo manda. Si solo llegó el texto, se busca su Id.
    IF NEW.idtipoincidencia IS NOT NULL THEN
        SELECT t.nombre INTO v_nombre_tipo FROM tiposincidencia t WHERE t.idtipoincidencia = NEW.idtipoincidencia;
        IF v_nombre_tipo IS NOT NULL THEN
            NEW.tipoincidencia := v_nombre_tipo::text;
        END IF;
    ELSIF NEW.tipoincidencia IS NOT NULL THEN
        SELECT t.idtipoincidencia, t.nombre INTO NEW.idtipoincidencia, v_nombre_tipo
        FROM tiposincidencia t WHERE t.nombre = btrim(NEW.tipoincidencia)::citext;
        IF v_nombre_tipo IS NOT NULL THEN
            NEW.tipoincidencia := v_nombre_tipo::text;
        END IF;
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF NEW.idtecnicoasignado IS NOT NULL THEN
            NEW.fechaasignacion       := COALESCE(NEW.fechaasignacion, LOCALTIMESTAMP);
            NEW.fechaprimerarespuesta := COALESCE(NEW.fechaprimerarespuesta, LOCALTIMESTAMP);
        END IF;
    ELSE
        SELECT e.nombre INTO v_anterior_estado FROM estados e WHERE e.idestado = OLD.idestado;

        -- Asignación (o reasignación): cuenta desde ahora y reinicia el SLA de "En Proceso"
        IF NEW.idtecnicoasignado IS DISTINCT FROM OLD.idtecnicoasignado THEN
            IF NEW.idtecnicoasignado IS NULL THEN
                NEW.fechaasignacion := NULL;
            ELSE
                NEW.fechaasignacion := LOCALTIMESTAMP;
            END IF;
            NEW.escaladoslaproceso := FALSE;
        END IF;

        -- Primera respuesta: la primera vez que se toma el ticket o sale de Pendiente
        IF NEW.fechaprimerarespuesta IS NULL AND (
               (OLD.idtecnicoasignado IS NULL AND NEW.idtecnicoasignado IS NOT NULL)
            OR (v_anterior_estado = 'Pendiente' AND v_nuevo_estado IS DISTINCT FROM 'Pendiente')) THEN
            NEW.fechaprimerarespuesta := LOCALTIMESTAMP;
        END IF;

        -- Reapertura: vuelve a contar el SLA
        IF v_anterior_estado IN ('Resuelto', 'Cerrado', 'Anulado')
           AND v_nuevo_estado IN ('Pendiente', 'En Proceso') THEN
            NEW.escaladosla        := FALSE;
            NEW.escaladoslaproceso := FALSE;
        END IF;
    END IF;

    -- Fecha de solución solo en Resuelto/Cerrado
    IF v_nuevo_estado IN ('Resuelto', 'Cerrado') THEN
        NEW.fechasolucion := COALESCE(NEW.fechasolucion, LOCALTIMESTAMP);
    ELSE
        NEW.fechasolucion := NULL;
    END IF;

    RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS trg_incidencias_reglas ON incidencias;
CREATE TRIGGER trg_incidencias_reglas
    BEFORE INSERT OR UPDATE ON incidencias
    FOR EACH ROW EXECUTE FUNCTION tg_incidencias_reglas();

