    p_tipoincidencia    VARCHAR,
    p_descripcion       TEXT,
    p_idprioridad       INT,
    p_idestado          INT,
    p_idtecnicoasignado INT  DEFAULT NULL,
    p_observaciones     TEXT DEFAULT NULL,
    p_idtipoincidencia  INT  DEFAULT NULL,
    p_idusuarioreporta  INT  DEFAULT NULL)
RETURNS INT LANGUAGE sql AS $$
    INSERT INTO incidencias (empleado, idarea, tipoincidencia, descripcion, idprioridad, idestado,
                             idtecnicoasignado, observaciones, idtipoincidencia, idusuarioreporta)
