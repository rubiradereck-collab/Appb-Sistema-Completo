-- 5 intentos fallidos => bloqueo de 5 minutos
CREATE OR REPLACE FUNCTION sp_usuarios_registrarintentofallido(p_idusuario INT)
RETURNS void LANGUAGE sql AS $$
    UPDATE usuarios
    SET intentosfallidos = intentosfallidos + 1,
        bloqueadohasta = CASE
            WHEN intentosfallidos + 1 >= 5 THEN LOCALTIMESTAMP + INTERVAL '5 minutes'
            ELSE bloqueadohasta
        END
    WHERE idusuario = p_idusuario;
$$;

CREATE OR REPLACE FUNCTION sp_usuarios_resetearintentos(p_idusuario INT)
RETURNS void LANGUAGE sql AS $$
    UPDATE usuarios
    SET intentosfallidos = 0,
        bloqueadohasta = NULL
    WHERE idusuario = p_idusuario;
$$;

