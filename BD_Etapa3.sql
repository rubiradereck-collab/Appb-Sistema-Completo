-- Usuarios: se agrega idarea al final de las columnas (las versiones anteriores
-- del escritorio piden columnas por nombre, así que siguen funcionando).
DROP FUNCTION IF EXISTS sp_usuarios_listar();
CREATE FUNCTION sp_usuarios_listar()
RETURNS TABLE (idusuario INT, nombre VARCHAR, apellido VARCHAR, correo CITEXT, usuario CITEXT,
               password VARCHAR, rol CITEXT, estado BOOLEAN, telegramchatid BIGINT,
               intentosfallidos INT, bloqueadohasta TIMESTAMP, fotoperfil BYTEA,
               idarea INT, nombrearea CITEXT)
LANGUAGE sql STABLE AS $$
    SELECT u.idusuario, u.nombre, u.apellido, u.correo, u.usuario, u.password, u.rol, u.estado,
           u.telegramchatid, u.intentosfallidos, u.bloqueadohasta, u.fotoperfil,
           u.idarea, a.nombrearea
    FROM usuarios u
    LEFT JOIN areas a ON a.idarea = u.idarea
    ORDER BY u.apellido, u.nombre ASC;
$$;

DROP FUNCTION IF EXISTS sp_usuarios_login(CITEXT);
CREATE FUNCTION sp_usuarios_login(p_usuario CITEXT)
RETURNS TABLE (idusuario INT, nombre VARCHAR, apellido VARCHAR, correo CITEXT, usuario CITEXT,
               password VARCHAR, rol CITEXT, estado BOOLEAN, telegramchatid BIGINT,
               intentosfallidos INT, bloqueadohasta TIMESTAMP, fotoperfil BYTEA,
               idarea INT, nombrearea CITEXT)
LANGUAGE sql STABLE AS $$
    SELECT u.idusuario, u.nombre, u.apellido, u.correo, u.usuario, u.password, u.rol, u.estado,
           u.telegramchatid, u.intentosfallidos, u.bloqueadohasta, u.fotoperfil,
           u.idarea, a.nombrearea
    FROM usuarios u
    LEFT JOIN areas a ON a.idarea = u.idarea
    WHERE u.usuario = p_usuario
