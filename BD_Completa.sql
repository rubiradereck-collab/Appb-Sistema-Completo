CREATE TABLE areas (
    idarea      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombrearea  CITEXT NOT NULL CHECK (char_length(nombrearea) <= 100)
);

CREATE TABLE estados (
    idestado    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      CITEXT NOT NULL CHECK (char_length(nombre) <= 50)
);

CREATE TABLE prioridades (
    idprioridad INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      CITEXT NOT NULL CHECK (char_length(nombre) <= 50)
);

CREATE TABLE guias (
    idguia      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo      VARCHAR(150) NOT NULL,
    problema    TEXT NOT NULL,
    solucion    TEXT NOT NULL
);

CREATE TABLE usuarios (
    idusuario        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL,
    apellido         VARCHAR(100) NOT NULL,
    correo           CITEXT NOT NULL CHECK (char_length(correo) <= 150),
    usuario          CITEXT NOT NULL CHECK (char_length(usuario) <= 50),
    password         VARCHAR(255) NOT NULL,
    rol              CITEXT NOT NULL CHECK (char_length(rol) <= 50),
    estado           BOOLEAN NOT NULL DEFAULT TRUE,
    telegramchatid   BIGINT NULL,
    intentosfallidos INT NOT NULL DEFAULT 0,
    bloqueadohasta   TIMESTAMP NULL,
    fotoperfil       BYTEA NULL,
    CONSTRAINT uq_usuarios_correo  UNIQUE (correo),
    CONSTRAINT uq_usuarios_usuario UNIQUE (usuario)
);

CREATE TABLE incidencias (
    idincidencia      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha             TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    empleado          VARCHAR(150) NOT NULL,
    idarea            INT NOT NULL,
    tipoincidencia    VARCHAR(100) NOT NULL,
    descripcion       TEXT NOT NULL,
    idprioridad       INT NOT NULL,
    idestado          INT NOT NULL,
    idtecnicoasignado INT NULL,
    fechasolucion     TIMESTAMP NULL,
    observaciones     TEXT NULL,
    -- Igual que en SQL Server: 'Solicitud-' + RIGHT('00000' + id, 5)
    numeroticket      VARCHAR(20) GENERATED ALWAYS AS ('Solicitud-' || right('00000' || idincidencia::text, 5)) STORED,
    escaladosla       BOOLEAN NOT NULL DEFAULT FALSE,
    filaversion       BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT fk_incidencias_areas       FOREIGN KEY (idarea)            REFERENCES areas (idarea),
    CONSTRAINT fk_incidencias_estados     FOREIGN KEY (idestado)          REFERENCES estados (idestado),
    CONSTRAINT fk_incidencias_prioridades FOREIGN KEY (idprioridad)       REFERENCES prioridades (idprioridad),
    CONSTRAINT fk_incidencias_tecnico     FOREIGN KEY (idtecnicoasignado) REFERENCES usuarios (idusuario)
);

CREATE TABLE auditoria (
    idauditoria   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha         TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    idusuario     INT NULL,
    nombreusuario VARCHAR(150) NOT NULL,
    accion        VARCHAR(50) NOT NULL,
    entidad       VARCHAR(50) NOT NULL,
    entidadid     INT NULL,
    detalle       TEXT NULL,
    CONSTRAINT fk_auditoria_usuarios FOREIGN KEY (idusuario) REFERENCES usuarios (idusuario)
);

CREATE TABLE reportesmensualesenviados (
    idreporte  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio       INT NOT NULL,
    mes        INT NOT NULL,
    fechaenvio TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT uq_reportemensual UNIQUE (anio, mes)
);

CREATE TABLE telegrammensajes (
    idincidencia INT NOT NULL,
    chatid       BIGINT NOT NULL,
    messageid    INT NOT NULL,
    CONSTRAINT fk_telegrammensajes_incidencias FOREIGN KEY (idincidencia)
        REFERENCES incidencias (idincidencia) ON DELETE CASCADE
);

