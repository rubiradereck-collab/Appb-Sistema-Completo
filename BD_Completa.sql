/* ============================================================================
   CONTROL DE CONCURRENCIA (reemplazo de rowversion)
   ============================================================================ */

CREATE OR REPLACE FUNCTION tg_incidencias_filaversion() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.filaversion := OLD.filaversion + 1;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_incidencias_filaversion
    BEFORE UPDATE ON incidencias
    FOR EACH ROW EXECUTE FUNCTION tg_incidencias_filaversion();

