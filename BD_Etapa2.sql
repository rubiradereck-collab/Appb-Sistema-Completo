-- Se revisan todas las tablas: solo se adelanta la secuencia, nunca se retrocede.
DO $$
DECLARE
    t RECORD;
    v_max BIGINT;
    v_ultimo BIGINT;
    v_usado BOOLEAN;
BEGIN
    FOR t IN
        SELECT c.table_name, c.column_name
        FROM information_schema.columns c
        WHERE c.table_schema = 'public' AND c.is_identity = 'YES'
    LOOP
        EXECUTE format('SELECT COALESCE(MAX(%I), 0) FROM %I', t.column_name, t.table_name) INTO v_max;
        EXECUTE format('SELECT last_value, is_called FROM %s', pg_get_serial_sequence(t.table_name, t.column_name))
            INTO v_ultimo, v_usado;
        IF v_max > 0 AND (v_max > v_ultimo OR (v_max = v_ultimo AND NOT v_usado)) THEN
            PERFORM setval(pg_get_serial_sequence(t.table_name, t.column_name), v_max, TRUE);
            RAISE NOTICE 'Secuencia de % ajustada a %.', t.table_name, v_max;
        END IF;
    END LOOP;
END
$$;

