-- El parámetro es CITEXT para que 'Admin' y 'admin' coincidan, como en SQL Server
CREATE OR REPLACE FUNCTION sp_usuarios_login(p_usuario CITEXT)
RETURNS TABLE (idusuario INT, nombre VARCHAR, apellido VARCHAR, correo CITEXT, usuario CITEXT,
               password VARCHAR, rol CITEXT, estado BOOLEAN, telegramchatid BIGINT,
               intentosfallidos INT, bloqueadohasta TIMESTAMP, fotoperfil BYTEA)
LANGUAGE sql STABLE AS $$
    SELECT u.idusuario, u.nombre, u.apellido, u.correo, u.usuario, u.password, u.rol, u.estado,
           u.telegramchatid, u.intentosfallidos, u.bloqueadohasta, u.fotoperfil
    FROM usuarios u
    WHERE u.usuario = p_usuario
      AND u.estado = TRUE;
$$;

