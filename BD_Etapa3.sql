-- Registra un envío y sus guías; devuelve el Id del envío
CREATE OR REPLACE FUNCTION sp_guiasenvios_registrar(
    p_idusuario          INT,
    p_nombreusuario      VARCHAR,
    p_canal              VARCHAR,
    p_tipodestino        VARCHAR,
    p_idarea             INT,
    p_destinatarios      TEXT,
    p_totaldestinatarios INT,
    p_idsguias           INT[])
RETURNS INT LANGUAGE plpgsql AS $$
DECLARE
    v_id INT;
BEGIN
    INSERT INTO guiasenvios (idusuario, nombreusuario, canal, tipodestino, idarea, destinatarios, totaldestinatarios)
    VALUES (p_idusuario, p_nombreusuario, p_canal, p_tipodestino, p_idarea, p_destinatarios, p_totaldestinatarios)
    RETURNING idenvio INTO v_id;

    INSERT INTO guiasenviosdetalle (idenvio, idguia, titulo)
    SELECT v_id, g.idguia, g.titulo
    FROM guias g
    WHERE g.idguia = ANY (p_idsguias);

    RETURN v_id;
END
$$;

CREATE OR REPLACE FUNCTION sp_guiasenvios_listar()
RETURNS TABLE (idenvio INT, fecha TIMESTAMP, idusuario INT, nombreusuario VARCHAR, canal VARCHAR,
               tipodestino VARCHAR, idarea INT, nombrearea CITEXT, destinatarios TEXT,
               totaldestinatarios INT, totalguias INT, guias TEXT)
LANGUAGE sql STABLE AS $$
    SELECT e.idenvio, e.fecha, e.idusuario, e.nombreusuario, e.canal, e.tipodestino, e.idarea, a.nombrearea,
           e.destinatarios, e.totaldestinatarios,
           (SELECT COUNT(*)::int FROM guiasenviosdetalle d WHERE d.idenvio = e.idenvio),
           (SELECT string_agg(d.titulo, ' | ' ORDER BY d.titulo) FROM guiasenviosdetalle d WHERE d.idenvio = e.idenvio)
    FROM guiasenvios e
    LEFT JOIN areas a ON a.idarea = e.idarea
    ORDER BY e.fecha DESC;
$$;

-- Incidencias: se agregan la calificación y su fecha al final
DROP FUNCTION IF EXISTS sp_incidencias_listar();
CREATE FUNCTION sp_incidencias_listar()
RETURNS TABLE (idincidencia INT, numeroticket VARCHAR, fecha TIMESTAMP, empleado VARCHAR,
               idarea INT, nombrearea CITEXT, tipoincidencia VARCHAR, descripcion TEXT,
               idprioridad INT, nombreprioridad CITEXT, idestado INT, nombreestado CITEXT,
               idtecnicoasignado INT, tecnicoasignado VARCHAR, fechasolucion TIMESTAMP,
               observaciones TEXT, filaversion BYTEA,
               idtipoincidencia INT, idusuarioreporta INT,
               fechaasignacion TIMESTAMP, fechaprimerarespuesta TIMESTAMP,
               calificacion SMALLINT, fechacalificacion TIMESTAMP)
LANGUAGE sql STABLE AS $$
    SELECT
        i.idincidencia, i.numeroticket, i.fecha, i.empleado,
        i.idarea, a.nombrearea, i.tipoincidencia, i.descripcion,
        i.idprioridad, p.nombre, i.idestado, e.nombre,
        i.idtecnicoasignado, (u.nombre || ' ' || u.apellido)::VARCHAR, i.fechasolucion,
        i.observaciones, int8send(i.filaversion),
        i.idtipoincidencia, i.idusuarioreporta,
        i.fechaasignacion, i.fechaprimerarespuesta,
        i.calificacion, i.fechacalificacion
    FROM incidencias i
    INNER JOIN areas a       ON i.idarea = a.idarea
    INNER JOIN prioridades p ON i.idprioridad = p.idprioridad
    INNER JOIN estados e     ON i.idestado = e.idestado
    LEFT JOIN usuarios u     ON i.idtecnicoasignado = u.idusuario
    ORDER BY i.fecha DESC;
$$;

-- Califica un ticket. Devuelve:
--   1 = guardado
--   0 = no corresponde (no lo reportó ese usuario, no está Resuelto/Cerrado o no existe)
--   2 = ya tenía calificación
CREATE OR REPLACE FUNCTION sp_incidencias_calificar(p_idincidencia INT, p_idusuario INT, p_calificacion INT)
RETURNS INT LANGUAGE plpgsql AS $$
DECLARE
    v_inc      RECORD;
    v_nombre   TEXT;
    v_es_suya  BOOLEAN;
BEGIN
    IF p_calificacion IS NULL OR p_calificacion NOT BETWEEN 1 AND 5 THEN
        RAISE EXCEPTION 'La calificación debe estar entre 1 y 5.';
    END IF;

    SELECT i.idusuarioreporta, i.empleado, i.calificacion, e.nombre AS estado
    INTO v_inc
    FROM incidencias i JOIN estados e ON e.idestado = i.idestado
    WHERE i.idincidencia = p_idincidencia
    FOR UPDATE OF i;

    IF NOT FOUND OR v_inc.estado NOT IN ('Resuelto', 'Cerrado') THEN
        RETURN 0;
    END IF;

    IF v_inc.idusuarioreporta IS NOT NULL THEN
        v_es_suya := v_inc.idusuarioreporta = p_idusuario;
    ELSE
        SELECT lower(btrim(u.nombre) || ' ' || btrim(u.apellido)) INTO v_nombre FROM usuarios u WHERE u.idusuario = p_idusuario;
        v_es_suya := v_nombre IS NOT NULL AND v_nombre = lower(btrim(v_inc.empleado));
    END IF;

    IF NOT v_es_suya THEN
        RETURN 0;
    END IF;
    IF v_inc.calificacion IS NOT NULL THEN
        RETURN 2;
    END IF;

    UPDATE incidencias
    SET calificacion = p_calificacion, fechacalificacion = LOCALTIMESTAMP
    WHERE idincidencia = p_idincidencia;
    RETURN 1;
END
$$;

-- Línea base
CREATE OR REPLACE FUNCTION sp_lineabase_obtener()
RETURNS TABLE (idlineabase INT, fecharegistro TIMESTAMP, nombreusuario VARCHAR, periodo VARCHAR,
               totalincidencias INT, tiempopromedioresolucionhoras NUMERIC, tiempoprimerarespuestahoras NUMERIC,
               porcentajeslacumplido NUMERIC, satisfaccionpromedio NUMERIC, fuente VARCHAR, observaciones TEXT)
LANGUAGE sql STABLE AS $$
    SELECT l.idlineabase, l.fecharegistro, l.nombreusuario, l.periodo,
           l.totalincidencias, l.tiempopromedioresolucionhoras, l.tiempoprimerarespuestahoras,
           l.porcentajeslacumplido, l.satisfaccionpromedio, l.fuente, l.observaciones
    FROM lineabase l
    ORDER BY l.fecharegistro DESC, l.idlineabase DESC
    LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION sp_lineabase_guardar(
    p_idusuario                     INT,
    p_nombreusuario                 VARCHAR,
    p_periodo                       VARCHAR,
    p_totalincidencias              INT,
    p_tiempopromedioresolucionhoras NUMERIC,
    p_tiempoprimerarespuestahoras   NUMERIC,
    p_porcentajeslacumplido         NUMERIC,
    p_satisfaccionpromedio          NUMERIC,
    p_fuente                        VARCHAR,
    p_observaciones                 TEXT)
RETURNS INT LANGUAGE sql AS $$
    INSERT INTO lineabase (idusuario, nombreusuario, periodo, totalincidencias, tiempopromedioresolucionhoras,
                           tiempoprimerarespuestahoras, porcentajeslacumplido, satisfaccionpromedio, fuente, observaciones)
    VALUES (p_idusuario, p_nombreusuario, p_periodo, p_totalincidencias, p_tiempopromedioresolucionhoras,
            p_tiempoprimerarespuestahoras, p_porcentajeslacumplido, p_satisfaccionpromedio, p_fuente, p_observaciones)
    RETURNING idlineabase;
$$;

