    porcentajeslacumplido        NUMERIC(5,2)  NULL CHECK (porcentajeslacumplido BETWEEN 0 AND 100),
    satisfaccionpromedio         NUMERIC(3,2)  NULL CHECK (satisfaccionpromedio BETWEEN 1 AND 5),
    fuente                       VARCHAR(200)  NULL,
    observaciones                TEXT          NULL,
    CONSTRAINT fk_lineabase_usuarios FOREIGN KEY (idusuario) REFERENCES usuarios (idusuario) ON DELETE SET NULL
