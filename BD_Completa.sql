-- Devuelve 1 = asignado con éxito, 0 = ya lo tomó otro técnico
CREATE OR REPLACE FUNCTION sp_incidencias_asignartecnicotelegram(
    p_idincidencia INT, p_idtecnico INT, p_idestadoenproceso INT)
RETURNS INT LANGUAGE plpgsql AS $$
BEGIN
    -- El WHERE hace la verificación y la asignación en un solo paso atómico
    UPDATE incidencias
    SET idtecnicoasignado = p_idtecnico,
        idestado          = p_idestadoenproceso
    WHERE incidencias.idincidencia = p_idincidencia
      AND (incidencias.idtecnicoasignado IS NULL OR incidencias.idtecnicoasignado = 0);

    IF FOUND THEN
        RETURN 1;
    END IF;
    RETURN 0;
END
$$;

-- Devuelve 1 = actualizado, 0 = la incidencia no pertenece a ese técnico
CREATE OR REPLACE FUNCTION sp_incidencias_actualizarestadotelegram(
    p_idincidencia INT, p_idtecnico INT, p_idnuevoestado INT, p_observaciones TEXT)
RETURNS INT LANGUAGE plpgsql AS $$
BEGIN
    UPDATE incidencias
    SET idestado      = p_idnuevoestado,
        observaciones = p_observaciones,
        fechasolucion = CASE
            WHEN p_idnuevoestado IN (SELECT e.idestado FROM estados e WHERE e.nombre IN ('Resuelto', 'Cerrado'))
            THEN LOCALTIMESTAMP
            ELSE incidencias.fechasolucion
        END
    WHERE incidencias.idincidencia = p_idincidencia
      AND incidencias.idtecnicoasignado = p_idtecnico;

    IF FOUND THEN
        RETURN 1;
    END IF;
    RETURN 0;
END
$$;

