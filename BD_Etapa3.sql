ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS idarea INT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_usuarios_areas') THEN
        -- Si se borra el área, el usuario queda sin área (no se borra el usuario)
        ALTER TABLE usuarios ADD CONSTRAINT fk_usuarios_areas
            FOREIGN KEY (idarea) REFERENCES areas (idarea) ON DELETE SET NULL;
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS ix_usuarios_idarea ON usuarios (idarea);

-- Datos existentes: el área en la que el usuario ha reportado más tickets
-- (solo usuarios sin área y solo si ya tienen tickets enlazados).
UPDATE usuarios u
SET idarea = x.idarea
FROM (
    SELECT DISTINCT ON (i.idusuarioreporta) i.idusuarioreporta, i.idarea
    FROM incidencias i
    WHERE i.idusuarioreporta IS NOT NULL
    GROUP BY i.idusuarioreporta, i.idarea
    ORDER BY i.idusuarioreporta, COUNT(*) DESC, MAX(i.fecha) DESC
) x
WHERE u.idusuario = x.idusuarioreporta
  AND u.idarea IS NULL;

