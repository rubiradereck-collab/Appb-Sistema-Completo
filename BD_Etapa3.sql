      Si el ticket se reabre, la calificación se borra y se vuelve a pedir.
   5. lineabase: cifras de antes del sistema para el informe final.

   Cómo ejecutarlo: como usuario postgres, en la base dbincidencias, después de
   BD_Etapa2.sql. Haz un respaldo antes. Se puede volver a ejecutar sin problema.

   Instalación nueva: BD_Completa.sql -> BD_Etapa2.sql -> BD_Etapa3.sql
                      -> BD_Datos_Iniciales.sql -> BD_Seguridad_Roles.sql
   ============================================================================ */

