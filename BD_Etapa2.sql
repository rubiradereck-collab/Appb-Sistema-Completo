            p_idtecnicoasignado, p_observaciones, p_idtipoincidencia, p_idusuarioreporta)
    RETURNING idincidencia;
$$;

DROP FUNCTION IF EXISTS sp_incidencias_modificar(INT, VARCHAR, INT, VARCHAR, TEXT, INT, INT, INT, TIMESTAMP, TEXT, BYTEA);
DROP FUNCTION IF EXISTS sp_incidencias_modificar(INT, VARCHAR, INT, VARCHAR, TEXT, INT, INT, INT, TIMESTAMP, TEXT, BYTEA, INT);
CREATE FUNCTION sp_incidencias_modificar(
    p_idincidencia        INT,
    p_empleado            VARCHAR,
    p_idarea              INT,
    p_tipoincidencia      VARCHAR,
    p_descripcion         TEXT,
    p_idprioridad         INT,
    p_idestado            INT,
    p_idtecnicoasignado   INT,
    p_fechasolucion       TIMESTAMP,
    p_observaciones       TEXT,
    p_filaversionoriginal BYTEA,
    p_idtipoincidencia    INT DEFAULT NULL)
RETURNS INT LANGUAGE plpgsql AS $$
DECLARE
    v_filas INT;
BEGIN
    -- idusuarioreporta no se toca: lo fija quien crea el ticket
    UPDATE incidencias
    SET empleado          = p_empleado,
        idarea            = p_idarea,
        tipoincidencia    = p_tipoincidencia,
        -- NULL = escritorio anterior: el trigger busca el Id por el nombre
        idtipoincidencia  = p_idtipoincidencia,
        descripcion       = p_descripcion,
        idprioridad       = p_idprioridad,
        idestado          = p_idestado,
        idtecnicoasignado = p_idtecnicoasignado,
        fechasolucion     = p_fechasolucion,
        observaciones     = p_observaciones
    WHERE incidencias.idincidencia = p_idincidencia
      AND int8send(incidencias.filaversion) = p_filaversionoriginal;

    GET DIAGNOSTICS v_filas = ROW_COUNT;
    RETURN v_filas;
END
$$;

/* ----------------------------------------------------------------------------
   8. Permisos
   Las funciones recién creadas no tienen los permisos de BD_Seguridad_Roles.sql:
